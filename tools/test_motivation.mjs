import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const source=script.slice(script.indexOf('function todayKey()'),script.indexOf('function day(k)'))+
  script.slice(script.indexOf('const RECORD_BADGES='),script.indexOf('function hashOf(s)'));
const context=vm.createContext({DB:{days:{},weights:{},profile:{goalWeight:65}}});
vm.runInContext(source+'\nfunction todayKey(){return "2026-09-27";}\nfunction labelShort(k){return k.slice(5);}',context);
const run=code=>vm.runInContext(code,context);
assert.equal(run('journeyStats("2026-09-27").total'),0);
assert.equal(run('weightWindow("2026-09-27").avg'),null);
run('DB.weights={"2026-09-25":70,"2026-09-26":71,"2026-09-28":99};');
assert.equal(run('journeyStats("2026-09-27").streak'),2,'today pending preserves yesterday streak');
assert.equal(run('journeyStats("2026-09-27").total'),2,'future values excluded');
assert.equal(run('weightWindow("2026-09-27").avg'),null,'two values are insufficient');
run('DB.weights["2026-09-27"]=72;DB.days["2026-09-27"]={meals:[{}],exs:[{}]};');
assert.equal(run('weightWindow("2026-09-27").avg'),71,'missing dates are not zero-filled');
assert.equal(run('journeyStats("2026-09-27").total'),3,'multiple kinds on same day count once');
run('DB.weights["2026-09-19"]=73;DB.weights["2026-09-20"]=74;DB.weights["2026-09-18"]=72;');
assert.equal(run('weightTrend("2026-09-27").delta'),-2,'non-overlapping calendar windows');
assert.equal(run('weightTrend("2026-09-27").progress'),null,'overlapping baseline is not used');
run('DB.weights={"2026-09-01":75,"2026-09-02":76,"2026-09-03":74,"2026-09-25":70,"2026-09-26":71,"2026-09-27":72};');
assert.equal(run('weightTrend("2026-09-27").progress'),40);
assert.equal(run('journeyStats("2026-09-25").resumed'),true);
run('DB.profile.goalWeight=80;');
assert.equal(run('weightTrend("2026-09-27").progress'),null,'no misleading weight-loss progress for higher target');
const before=JSON.stringify(context.DB);
run('journeyHTML("2026-09-27",true);trendHTML("2026-09-27");');
assert.equal(JSON.stringify(context.DB),before,'render helpers must not mutate saved data');
console.log('Motivation checks passed: empty data, streak, deduplication, date windows, goals, non-mutation.');
